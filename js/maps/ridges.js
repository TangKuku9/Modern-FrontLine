// 盘山路的走廊宽度：ramp() 与路面精修**必须用同一组**，否则两层之间会留一圈
// "修过的路 ↔ 没修的山坡"的断层，导航网格就把它切掉（实测断层处坡度 0.45~0.56）。
const RAMP_W = 22, RAMP_E = 48;
// RAMP_FREEZE：折线开头这么长的一段内不抬升（米）。台地范围内地形已是设计高，
// 路在这里什么也不改；出了台地才开始爬。
const RAMP_FREEZE = 40;

// 道路走廊：把中频噪声偶然甩出来的陡坡抹平。中频噪声会长出 1.0+ 的陡坎
// （实测营地正西 x=-36..-49 一段坡度 1.24）—— 它不属于设计，是噪声的副产品，
// 却实实在在把营区和西侧出生区切开了。把沿线当成"往基准面削"来处理：
// 只削峰、不筑坝（筑坝会造出没人设计过的山头）。半宽要够宽，窄走廊两侧会留新坎。
//
// **走廊要按"玩家真会走的路线"布，不是按两个出生点直连。** 早一版两条走廊只连
// (6,-20)→(-152,6) 与 (-2,22)→(150,-6)，可实测西侧从出生点往东南走会在 x≈-100
// 撞上一道 0.48~0.85 的坎 —— 那道坎在 z≈42，走廊在 z≈8，两者差了 34m，擦肩而过。
// 后果是导航网格把西半张图整个切出去，A* 从西出生点到南丘直接报"无路径"。
// 第三条走廊专门走那条实际通路：西出生平台 → 营区西南角 → 接第一条走廊。
const CORRIDOR = [
  [[6, -20], [-40, 2], [-100, 8], [-152, 6]],
  [[-2, 22], [40, 16], [100, 2], [150, -6]],
  // 西侧联络线：把西出生平台接进营区。实测这条线上曾有 0.85 的断坎。
  [[-158, 6], [-132, 22], [-108, 34], [-86, 34], [-62, 30], [-38, 22]],
];
const CORRIDOR_W = [26, 52];   // 半宽 / 完全过渡出去的距离

// 台地豁免：这些圆内不做走廊削平、也不做路面精修。
// 为什么要豁免：走廊往 8m 基准面削，会把营区台地（设计高 10m）与高地顶（30/32m）
// 一起削走 —— 实测营区被削到 8m、高地顶 18m 内出现 5m 高差（塔腿悬空）。
// 反过来路面精修也不能进台地：盘山路最后一折的目标就是台顶高，让它的线性剖面在
// 台内继续生效，会把台顶拉出高低差。
//
// **半径只护住"要放塔的那一小块"，绝不能护住整个台地。**
// 这是踩过的坑：早一版取 26m（≈台地半径），结果盘山路的最后一段正好落在这个圈里，
// 路面精修被关掉，台缘那堵 8m 的坎没人修 —— 实测超限点 (-89,-75) **距路廊中心线 0m**
// 却仍是 0.59 的断路。豁免圈一大，就把唯一能修它的那道工序关了。
// 现在只护 12m（塔基 + 观察位），路面精修能一直修到台心，接缝不再无人负责。
// 营区不同 —— 它整个台面都要盖营房，豁免半径给到 34m（正好是营区台地半径）。
const PLATEAUS = [
  { x: SITE.north.x, z: SITE.north.z, r: 12 },
  { x: SITE.south.x, z: SITE.south.z, r: 12 },
  { x: SITE.camp.x, z: SITE.camp.z, r: 34 },
];
// 豁免权重：圆内 0（完全不修），到 r*2.4 回到 1。
// falloff(d, r, 2.4r) 本身就是"圈内=1、圈外=0"，所以**不要再写 1 - falloff** ——
// 那样取反了，台地中心拿到 1（照削不误）、圈外拿到 0（永不修），正好拧反。
function plateauGuard(x, z) {
  let g = 1;
  for (const p of PLATEAUS) {
    const t = falloff(Math.hypot(x - p.x, z - p.z), p.r, p.r * 2.4);
    if (t < g) g = t;
  }
  return g;
}

// 两张噪声：一张铺大起伏（主波长 ~120m），一张铺中频（~36m）。
// 波长按 SIZE 推而不是写死 —— 固定波长换一张更大的图就变成"一马平川"。
const nBig = new TileNoise(3101, 64);
const nMid = new TileNoise(6203, 64);

export function shape(x, z) {
  // ---- 1. 底：连绵起伏 ----
  // 两层叠加：大层定"哪一片是高地"，中层添"连绵"的碎起伏。
  const big = hillNoise(nBig, x, z, SIZE, SIZE * 0.34, 4, 0.5, 0.45) - 0.5;
  const mid = hillNoise(nMid, x, z, SIZE, SIZE * 0.10, 4, 0.5, 0.5) - 0.5;
  let h = Y.base + big * 15 + mid * 6.5;

  // ---- 2. 两处主高地 ----
// 高斯鼓包：顶圆、肩缓，走得上也退得回来。指数是 2 —— 用 4 会得到"台顶+断崖"。
// 半径给到 r*2.6（早一版 2.0）：鼓包自身要负责把 24~26m 的落差铺开，
// 台地只在顶上压平。若鼓包太陡（r*2.0 时台缘坡度 1.13），台地压得再平也没用——
// 陡坡在半径 40m 处，而盘山走廊只到 15m，两者接不上，南丘就成孤岛。
h += mound(x, z, SITE.north.x, SITE.north.z, SITE.north.r * 2.6, 24);
  h += mound(x, z, SITE.south.x, SITE.south.z, SITE.south.r * 2.6, 26);

  // ---- 3. 鞍部：把两座高地之间压低，形成一条明确可走的走廊 ----
  h -= 9 * falloff(Math.hypot(x - SITE.saddle.x, z - SITE.saddle.z), 26, 105);

  // ---- 4. 台地 ----
  // terrace 的 radius 是"完全平"的范围，edge 是"过渡到自然地形"的距离 —— 两者的差
  // 就是台地边坡的宽度，**它决定了山有多陡**。第一版 16 / 30：14m 的落差挤在 14m
  // 水平距离里，坡度 3.9（tan 76°），那不是台地是断崖，导航网格当场把山顶判成孤岛。
  // 现在 30 / 78：台顶是直径 60m 的真平台，边坡摊在 48m 上（坡度 ~0.5）。
  // 半径加大不是为了好看 —— 是为了让**边坡起点落在盘山路的控制范围之内**，
  // 两者同高对接，接缝处不再冒出一圈台阶（实测接缝坡度 1.1，山顶仍是孤岛）。
  // 台地半径 20m：台顶是直径 40m 的平台，够放一座瞭望塔 + 观察位。
  // 为什么不能再大：盘山走廊在山腰上会堆出一条"路堤"，它与原地形的接缝很陡。
  // 台地半径越大，这道接缝就越靠里、越难被路的高修平 —— 实测半径 31m 时南丘
  // 西南侧出现一圈 0.63 的陡坡，把上山的路自己变成了断路（塔在连通域里、路不在）。
  // 20m 的台顶 + 58m 的过渡（edge 78）：落差摊开，坡度 ~0.38，走得上去。
  h = terrace(h, x, z, SITE.north.x, SITE.north.z, 20, 78, Y.ridgeTop);
  h = terrace(h, x, z, SITE.south.x, SITE.south.z, 20, 80, Y.ridgeTop + 2);
  // 营区台地半径 40 —— **不是 28**。营房铺到离营心 36m（围墙 ±36、车场 z+26、
  // 直升机坪 (-26,-22)），半径 28 只盖住了中间一圈：实测最外圈的兵营脚下高差
  // 2.86m、直升机坪 3.85m，最陡 0.68 —— 房子直接骑在斜坡上，一角悬空一角埋土。
  // 40m 把所有营房足迹都圈进"完全平"的范围，实测兵营降到 0.74m、直升机坪 1.45m。
  h = terrace(h, x, z, SITE.camp.x, SITE.camp.z, 40, 78, Y.camp);
  // 弹药油料区在营区东南角 (26,16)，离营心 32m —— 落在 40m 圈边之外，噪声把它
  // 抬到了 13m（实测区内高差 3.37m）。它是平地堆放区，必须平，所以单独再压一块。
  h = terrace(h, x, z, SITE.depot.x, SITE.depot.z, 22, 44, Y.camp + 0.4);
  // 出生平台：图缘最容易被噪声甩出一个陡坡，出生点站在坡上会一路滑进图外。
  h = terrace(h, x, z, SITE.spawnA.x, SITE.spawnA.z, 17, 44, Y.spawn);
  h = terrace(h, x, z, SITE.spawnB.x, SITE.spawnB.z, 17, 44, Y.spawn);

  // ---- 5. 盘山路（压在台地之后：路要能改台地边缘的坡，否则接不上）----
  // 半宽 22m、过渡到 38m。数值是量出来的，不是猜的：走廊宽度 w 时它与原地形的
  // 接缝实测坡度约为中心线设计坡度的 1.6 倍，而设计爬升 0.20 → 接缝 0.32 < 0.42。
  // 早一版 15/26 配 0.26 的爬升，接缝实测 0.56~0.84，两条路都断。
  for (const r of RAMPS) h = rampFrom(h, x, z, r, RAMP_W, RAMP_E, RAMP_FREEZE);

  // ---- 6. 边界：把图缘压回平原，免得墙根处冒出半截悬崖 ----
  // 放在走廊之前：图缘那道"平原带"是给 bounds() 的墙兜底的，不能被走廊削穿。
  const k = falloff(Math.max(Math.abs(x), Math.abs(z)) / HALF, 0.86, 1.0);
  h = h * (1 - k) + Y.plain * k;

  // ---- 7. 道路走廊：抹平噪声陡坎（台地内豁免）----
  const guard = plateauGuard(x, z);
  for (const c of CORRIDOR) {
    let lo = Infinity;
    for (const [px, pz] of c) {
      const d = Math.hypot(x - px, z - pz);
      if (d < lo) lo = d;
    }
    const w = (1 - falloff(lo, CORRIDOR_W[0], CORRIDOR_W[1])) * guard;
    if (w > 0) h = h * (1 - w) + Y.road * w;   // 只削不筑
  }

  // ---- 8. 瞭望塔台面：重压一次，前七步谁都别想削它 ----
  // 塔是这张图上唯一"四条腿必须同时着地"的物件，而它是所有工序的终点：走廊会削它、
  // 路面精修会拉它、盘山走廊会压进它（实测塔周 13m 内被搞出 6.2m 高差 / 坡度 1.25，
  // 这样的塔腿是悬空的）。所以把塔基那一小块在这里重压一次。
  //
  // **顺序：它必须在"路面精修"之前，不是最后。** 这是踩过的最深的一个坑 ——
  // 终检式的"最后再压一次"看起来最保险，实测却是**最后一道加高**：逐工序复算
  // (-75,-53) 得到 20.75 → 23.76，路面精修辛苦修平的路被它重新推高 3m，
  // 于是那一段又变成 0.5 的陡坡（实测超限点距折线 0.4m，却在导航网格里被判断路）。
  // 放在精修之前，终压只负责"把台地顶保住"，接缝由精修统一收尾—— 各司其职。
  //
  // 过渡带 46m（不是 22）：平的范围小（半径 9m，够放塔）、过渡的范围大，
  // 20m 落差摊在 37m 上 ≈ 0.54，再由第 9 步精修压到 0.42 以下。
  h = terrace(h, x, z, SITE.north.x, SITE.north.z, 9, 46, Y.ridgeTop);
  h = terrace(h, x, z, SITE.south.x, SITE.south.z, 9, 46, Y.ridgeTop + 2);

  // ---- 9. 路面精修：盘山路上残留的起伏，凸起与凹陷都修（塔基内豁免）----
  // 走廊是"往基准面削"，可盘山路要一路爬升，削不得；山腰上残留的中小尺度噪声会卡在
  // 路中间。它**不全是凸起** —— 实测南坡道 (46,58) 是低 3m 的**凹坑**，早一版只削凸
  // 于是漏掉了它，路在那一截仍然断开。正确做法是双向收敛：往目标剖面拉，高削低填。
  //
  // **精修的半宽必须与 ramp 走廊一致**（RAMP_W / RAMP_E）。早一版这里是 5/12 而
  // 走廊是 15/26：走廊把中心 15m 修平了，精修只管 5m，于是 5~15m 之间留着
  // "修过的路 ↔ 没修的山坡"的断层 —— 实测超限点就落在这一圈上（坡度 0.45~0.56）。
  // 走廊负责大尺度，精修负责小尺度，两者边界重合才没有缝。
  //
  // 它是**最后一道工序**：台地终压、走廊、盘山路都已经被拉平/削过一遍，
  // 由它来统一收尾，接缝只此一处。
  for (const path of RAMPS) {
    let lo = Infinity, tgt = 0;
    for (let i = 0; i + 1 < path.length; i++) {
      const ax = path[i][0], az = path[i][1];
      const vx = path[i + 1][0] - ax, vz = path[i + 1][1] - az;
      const L2 = vx * vx + vz * vz;
      const s = L2 > 0 ? Math.max(0, Math.min(1, ((x - ax) * vx + (z - az) * vz) / L2)) : 0;
      const d = Math.hypot(x - (ax + vx * s), z - (az + vz * s));
      if (d < lo) { lo = d; tgt = path[i][2] + (path[i + 1][2] - path[i][2]) * s; }
    }
    if (lo < RAMP_E) h += (tgt - h) * (1 - falloff(lo, RAMP_W, RAMP_E)) * guard;
  }
  return h;
}
// 逐顶点色：草（噪声色斑）→ 碎石 → 裸岩（按坡度）→ 高处踩秃的土面 → 水泥盘山路
// → 据点磨损环/出生平台夯土 → 营区夯土。
// 路的画法与 CORRIDOR 是同一份坐标表 —— 颜色画在路上、物件摆在路旁，两边不会漂。
//
// color() 是逐顶点调用的（terrainStride 16m 一格），表达得动的最小斑块 ~30m：
// 双频值噪声，低频(~90m)定"这片坡是青是枯"，中频(~24m)碎裂亮度；更细的颗粒
// 交给 grass 底图（6m 一格）。再细就超出顶点网格了，硬塞只会采样成脏斑。
const cNoise = new TileNoise(71, 64);
const nAt = (x, z, freq) => cNoise.get(x / SIZE, z / SIZE, freq);
const sstep = (a, b, v) => { const t = clamp((v - a) / (b - a), 0, 1); return t * t * (3 - 2 * t); };

export function color(x, z, y, slope) {
  // 这组值是**乘在草贴图上的**，所以整体偏亮：顶点色压得太暗，360m 图上一整片
  // 丘陵就会糊成一块深褐（截图实测）。往 1.0 附近收，起伏与色带才读得出来。
  //
  // 草不再是一个死值（用户实测"山和地一片均匀绿"）：低频在 青草↔草↔枯草 之间
  // 挑大斑块，中频 ±5% 碎裂亮度。
  const macro = nAt(x, z, 4), mid = nAt(x, z, 15);
  let r, g, b;
  if (macro < 0.5) {                       // 青草 (0.60,0.80,0.52) → 草
    const t = macro * 2;
    r = 0.60 + 0.14 * t; g = 0.80 + 0.08 * t; b = 0.52 + 0.06 * t;
  } else {                                 // 草 → 枯草 (0.88,0.82,0.55)
    const t = macro * 2 - 1;
    r = 0.74 + 0.14 * t; g = 0.88 - 0.06 * t; b = 0.58 - 0.03 * t;
  }
  const br = 1 + (mid - 0.5) * 0.10;
  r *= br; g *= br; b *= br;

  // 坡度带：碎石档从 0.34 下探到 ~0.28（噪声抖动 ±0.05，别在网格上画出"等高线"），
  // 让丘陵上部普遍带一点碎石色；裸岩档保持 0.62 —— 视觉语义与物理对齐
  // （0.42 起是阻力带、0.85 以上真崖：裸岩"可以慢慢爬"，崖看着就不可爬）。
  // 裸岩加明度噪声，别是一块死灰。
  const j = (nAt(x + 31.7, z - 17.3, 22) - 0.5) * 0.10;
  const scree = sstep(0.26 + j, 0.34 + j, slope);
  const rockF = sstep(0.60 + j, 0.66 + j, slope);
  r += (0.90 - r) * scree; g += (0.83 - g) * scree; b += (0.62 - b) * scree;
  const rk = 1 + (nAt(x - 11.1, z + 23.9, 30) - 0.5) * 0.14;
  r += (0.86 * rk - r) * rockF; g += (0.82 * rk - g) * rockF; b += (0.76 * rk - b) * rockF;

  // 高处草稀（风大 + 踩秃），往土色偏
  const alt = Math.max(0, Math.min(1, (y - 16) / (Y.ridgeTop - 16 + 1)));
  r += (0.88 - r) * alt * 0.5; g += (0.82 - g) * alt * 0.5; b += (0.62 - b) * alt * 0.5;

  // 盘山路：**水泥硬化路面**（用户点名的方案）。草底图的蓝通道只有红的一半
  //（生成器里 b≈0.18、r≈0.47），纯灰顶点色乘出来仍偏绿 —— 蓝通道按底图色相
  // 反向补偿（×2.4，实拍定值）才能把绿抵成灰；路面再叠中频明度噪声，别一条死灰带。
  // 半宽 1.7/3.4 → 2.2/4.2：16m 顶点采样下 3.4m 的路被稀释得快看不见（俯瞰实测），
  // 加宽才读得出"有条能走车的路"。
  let onRoad = 0;
  for (const c of CORRIDOR) {
    for (let i = 0; i + 1 < c.length; i++) {
      const ax = c[i][0], az = c[i][1];
      const vx = c[i + 1][0] - ax, vz = c[i + 1][1] - az;
      const L2 = vx * vx + vz * vz;
      const t = L2 > 0 ? Math.max(0, Math.min(1, ((x - ax) * vx + (z - az) * vz) / L2)) : 0;
      const d = Math.hypot(x - (ax + vx * t), z - (az + vz * t));
      const w = 1 - falloff(d, 2.2, 4.2);
      if (w > onRoad) onRoad = w;
    }
  }
  if (onRoad > 0) {
    const cem = 0.80 + mid * 0.10;         // 0.80..0.90 磨损明度（水泥是中灰，不是白）
    r += (cem - r) * onRoad;
    g += (cem * 0.95 - g) * onRoad;
    b += (cem * 3.0 - b) * onRoad;
  }

  // 据点磨损环：旗子周围人踩车碾的秃斑 —— 顺带把"点在哪"画在地上（占点可读性）。
  for (const [fx, fz] of FLAG_POS) {
    const wf = 1 - falloff(Math.hypot(x - fx, z - fz), 5.5, 10.5);
    if (wf > 0) { r += (0.90 - r) * wf; g += (0.82 - g) * wf; b += (0.62 - b) * wf; }
  }
  // 出生平台夯土：与营区同款 —— 出站这一圈是"压过的地"，不再是草地上凭空一片平。
  for (const sp of [SITE.spawnA, SITE.spawnB]) {
    const wf = 1 - falloff(Math.hypot(x - sp.x, z - sp.z), sp.r * 0.75, sp.r * 1.08);
    if (wf > 0) { r += (0.90 - r) * wf; g += (0.82 - g) * wf; b += (0.62 - b) * wf; }
  }

  // 营区是"平整"的，地面被压成夯土：半径内往土黄偏
  const cf = 1 - falloff(Math.hypot(x - SITE.camp.x, z - SITE.camp.z), SITE.camp.r * 0.6, SITE.camp.r * 1.05);
  if (cf > 0) { r += (0.90 - r) * cf; g += (0.82 - g) * cf; b += (0.62 - b) * cf; }

  return [r, g, b];
}

export { CORRIDOR };