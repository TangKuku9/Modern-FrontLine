// 「双丘战区」高度场 —— **只在这里定义地形**，物件摆放见 maps.js 的 build()。
//
// 用户给的五条硬要求，逐条对应：
//   ① 超大型：360m 见方，是卡尔达什（200m）的 3.2 倍面积。
//   ② 连绵起伏的丘陵，作战范围大致为两处高地：两层噪声铺满全图的低幅丘陵，
//      再用两个高斯鼓包抬起两块主高地（北岭 / 南丘），两处之间留一道鞍部 ——
//      鞍部是刻意留的：它让"两地之间怎么走"成为一道真问题，而不是两块孤岛。
//   ③ 两处高地上都有瞭望塔：塔位在 shape 里被 terrace() 压平，否则四条腿高度不齐。
//   ④ 旁边一处较为平整的地方坐落着一个军营：中央台地（营区）压到近乎水平。
//   ⑤ 细节完善、物品丰富但不随意摆放：物件按"谁放在这儿为什么"分区，见 build()。
//
// 这份 shape 的**施工顺序**就是它的设计文档，每一步都在改上一步的成果：
//   噪声（起伏）→ 鼓包（两地）→ 鞍部（连接）→ 台地（压平）→ 盘山路（上山）
//   → 道路走廊（抹平噪声陡坎）→ 路面精修（削掉路上残疙瘩）→ 边界（收边）
// 顺序不能换：台地必须早于盘山路（路要改台边的坡），路面精修必须晚于走廊
//（否则会被走廊的基准面重新削平）。判据在 test/terrain.mjs。
