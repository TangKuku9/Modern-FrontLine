// HTML 转义的**唯一**一份实现。
//
// ── 为什么值得单独一个模块 ──
// 改动前这个仓库里同时住着三套口径不一的转义器：
//   js/main.js:35    只删 `<>` —— 连 `&` 都不转，所以字符串 `&lt;script&gt;` 会被
//                    浏览器**当成真实的标签再解析一次**，等于绕开了这道防线；
//   js/menu.js:50    转 `& < > "`，**不转单引号** —— 用 `'...'` 包属性值的那一格就漏了；
//   js/net/chat.mjs  五个都转（最全的那一份）。
// 分叉本身就是下一个洞的温床：同一个字符串走聊天是安全的、走记分板就不安全，而
// "哪一处用的是哪一份"没人说得清。所以收成一份，五个字符全转。
//
// ── 用在哪 ──
// **拼 innerHTML 的那一处**转，不要放在调用方：放在调用方的话，多一个调用点就多一次
// "忘了"（`js/hud.js` 的击杀提示就是这么漏的 —— weapon 由调用方转义、两个呼号裸着，
// 一半转一半不转，看着像"已经处理过了"）。
//
// ── 判据 ──
// test/net-audit.mjs 的 I 段：五个字符逐个钉、`&lt;` 不许被二次解析、非字符串输入不许抛、
// "js/ 下不许再出现第二份实现"的形状守卫；`chatRowHtml`（聊天）与
// `NetClient.scoreboardHTML`（记分板）走的是**行为**判据。HUD 那两个拼接点（killfeed /
// announce）在真 DOM 上量，见 test/state-leak.mjs 的 X 段。
export function escHtml(s) {
  return String(s == null ? '' : s).replace(/[&<>"']/g, c => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  }[c]));
}
